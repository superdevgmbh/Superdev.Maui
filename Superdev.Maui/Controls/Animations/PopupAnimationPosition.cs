namespace Superdev.Maui.Controls.Animations
{
    /// <summary>
    /// The position a popup animates from or to.
    /// </summary>
    public enum PopupAnimationPosition
    {
        /// <summary>The popup stays where it is laid out.</summary>
        Center,

        /// <summary>The popup moves in from or out to the left edge.</summary>
        Left,

        /// <summary>The popup moves in from or out to the top edge.</summary>
        Top,

        /// <summary>The popup moves in from or out to the right edge.</summary>
        Right,

        /// <summary>The popup moves in from or out to the bottom edge.</summary>
        Bottom,
    }
}
